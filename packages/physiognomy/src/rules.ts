/**
 * 관상 특징 → 공통 성향 척도.
 *
 * 각 규칙은 전통 관상의 십이궁 해석을 그대로 옮긴 것이다.
 * 다만 단정하지 않는다 — "부자가 된다"가 아니라 "재물을 담는 그릇이 크다고 본다"로 쓴다.
 * 근거에 원래 용어(궁 이름)를 남겨서, 나중에 사주 결과와 대조할 때
 * 어느 쪽이 무슨 말을 했는지 추적할 수 있게 한다.
 */

import type { TraitProfile, TraitSignal } from '../../traits/src/index.ts';
import { type FaceFeatures, FACE_SHAPE_LABEL } from './features.ts';

/** 세 단계를 점수로. mid는 신호를 내지 않는다 (특징 없음). */
const lv = (v: 'low' | 'mid' | 'high'): -1 | 0 | 1 => (v === 'high' ? 1 : v === 'low' ? -1 : 0);

export interface FaceCombo {
  name: string;
  evidence: string;
  text: string;
}

export interface PhysiognomyReading {
  profile: TraitProfile;
  /** 부위별 사람이 읽는 풀이 (10대목) */
  notes: { palace: string; text: string }[];
  /** 두 부위를 묶어 보는 대목 */
  combos: FaceCombo[];
  /** 두드러진 특징만 추린 것 */
  highlights: string[];
}

export function readFace(f: FaceFeatures): PhysiognomyReading {
  const signals: TraitSignal[] = [];
  const notes: { palace: string; text: string }[] = [];
  const combos: FaceCombo[] = [];

  const push = (axis: TraitSignal['axis'], score: number, evidence: string) => {
    if (score === 0) return;
    signals.push({ axis, score: Math.max(-2, Math.min(2, score)) as TraitSignal['score'], evidence });
  };

  // 1. 이마 — 관록궁
  const fw = lv(f.foreheadWidth);
  if (fw !== 0) {
    push('학습·직관', fw, `관록궁(이마)이 ${fw > 0 ? '넓다' : '좁다'}`);
    push('리더십', fw, `관록궁(이마)이 ${fw > 0 ? '넓다' : '좁다'}`);
  }
  notes.push({
    palace: '관록궁 (이마)',
    text: fw > 0
      ? '이마가 시원하고 넓은 편입니다. 관상에서는 이마를 관록궁(官祿宮)으로 보아, 배우고 헤아리는 직관과 총명함이 크고 사회적인 위치나 기회가 비교적 일찍 열리는 기운으로 해석합니다. 넓은 시야로 상황을 파악하며 뜻을 높게 품는 장점이 있습니다.'
      : fw < 0
        ? '이마가 아담하고 좁은 편입니다. 관상에서는 이론이나 명분보다 현장에서 직접 부딪치며 익히는 실천력이 강한 모양으로 봅니다. 일찍 자리를 정하기보다 실전 경험을 차곡차곡 쌓아 올리면서 뒤로 갈수록 든든하게 터를 닦아나가는 흐름으로 해석합니다.'
        : '이마는 넓지도 좁지도 않고 알맞게 균형을 이루고 있습니다. 관상에서는 관록궁이 한쪽으로 치우치지 않아 생각과 행동이 조화를 이루며, 무리한 욕심 없이 차분하게 자기 길을 찾아가는 순탄한 형세로 봅니다. 급격한 기복 없이 꾸준히 학습하고 성장하여 자신의 자리를 탄탄히 다져나가는 안정성을 지니고 있습니다.',
  });

  // 2. 눈썹 — 형제궁
  const bt = lv(f.browThickness);
  if (bt !== 0) {
    push('추진력', bt, `형제궁(눈썹)이 ${bt > 0 ? '짙다' : '옅다'}`);
    push('대인관계', bt, `형제궁(눈썹)이 ${bt > 0 ? '짙다' : '옅다'}`);
  }
  notes.push({
    palace: '형제궁 (눈썹)',
    text: bt > 0
      ? '눈썹이 짙고 기세가 뚜렷합니다. 관상에서는 형제궁(兄弟宮)으로 보아 동료나 주변 사람을 끌어모으는 활력과 결단력이 크다고 봅니다. 뜻을 세우면 힘차게 밀고 나가는 추진력이 있으며, 곁에 든든한 협력자를 두고 함께 움직일 때 장점이 더욱 살아납니다.'
      : bt < 0
        ? '눈썹이 부드럽고 옅은 편입니다. 관상에서는 다투거나 부딪치기보다는 유연하게 물러서며 조화를 이루는 편으로 봅니다. 많은 사람과 얽히기보다 진실한 소수와 깊고 담백한 관계를 맺으며, 섬세한 감각으로 주변을 배려하는 쪽에 알맞다고 해석합니다.'
        : '눈썹이 지나치게 짙거나 옅지 않고 적당한 결을 그리며 흐릅니다. 관상에서는 형제궁이 가지런하여 대인관계에서 기세가 과하여 상대를 누르지도 않고 위축되지도 않는 편안함을 준다고 봅니다. 주변 사람들과 원만하게 보조를 맞추면서 필요한 순간에 알맞게 힘을 싣는 유연한 처세가 돋보입니다.',
  });

  // 3. 눈 — 전택궁
  const es = lv(f.eyeSize);
  if (es !== 0) {
    push('대인관계', es, `전택궁(눈)이 ${es > 0 ? '크다' : '작다'}`);
    push('표현력', es, `전택궁(눈)이 ${es > 0 ? '크다' : '작다'}`);
    push('안정성', -es, `전택궁(눈)이 ${es > 0 ? '크다' : '작다'}`);
  }
  notes.push({
    palace: '전택궁 (눈)',
    text: es > 0
      ? '눈이 크고 맑은 편입니다. 관상에서는 전택궁(田宅宮)으로 보아 감정과 정감이 솔직하게 드러나며 사람을 끌어당기는 표현력이 풍부하다고 봅니다. 새로운 자극과 사람에 열려 있어 다정다감하지만, 마음의 출렁임이 있을 때는 차분히 중심을 잡는 것이 좋습니다.'
      : es < 0
        ? '눈이 아담하고 그윽한 편입니다. 관상에서는 속생각이나 감정을 쉽게 드러내지 않고 내면에 오래 갈무리하는 신중함으로 봅니다. 한번 목표나 원칙을 정하면 바깥 풍파에 쉽게 흔들리지 않고 묵묵히 자리를 지키며 완주하는 끈기가 있다고 해석합니다.'
        : '눈 크기가 너무 크거나 작지 않고 편안하게 자리 잡고 있습니다. 관상에서는 전택궁이 맑고 온화하여 상황을 차분하게 관찰하면서도 필요한 때 자기 뜻을 부드럽게 내보이는 중용의 눈으로 봅니다. 감정에 휩쓸리지 않으면서도 따뜻한 온기를 잃지 않고 사람을 대하는 안정된 시선을 품고 있습니다.',
  });

  // 4. 콧대 — 재백궁 상단
  const nb = lv(f.noseBridge);
  if (nb !== 0) {
    push('추진력', nb, `재백궁(콧대)이 ${nb > 0 ? '높다' : '낮다'}`);
    push('리더십', nb, `재백궁(콧대)이 ${nb > 0 ? '높다' : '낮다'}`);
  }
  notes.push({
    palace: '재백궁 (콧대)',
    text: nb > 0
      ? '콧대가 반듯하고 높은 편입니다. 관상에서는 콧대를 재백궁(財帛宮)의 기둥으로 보아, 자존감과 독립심이 강하고 자기 주관을 뚜렷하게 세우는 성정으로 해석합니다. 남에게 의지하기보다 스스로 판단하고 추진하여 길을 개척하는 기운이 두드러집니다.'
      : nb < 0
        ? '콧대가 완만하고 낮은 편입니다. 관상에서는 자기 고집을 무리하게 세우기보다 주변의 흐름에 부드럽게 순응하며 융합하는 모양새로 봅니다. 모나지 않고 유연하여 팀이나 조직 안에서 마찰을 줄이고 협력의 분위기를 이끌어내는 데 적합하다고 봅니다.'
        : '콧대가 지나치게 높거나 낮지 않고 반듯하게 가지런합니다. 관상에서는 재백궁의 중심 기둥이 안정되어 자기 주관을 단단히 지키면서도 타인의 의견을 편견 없이 수용하는 유연함으로 봅니다. 독단에 빠지지 않고 합리적이며 현실적인 타협점을 현명하게 찾아내는 원만한 리더십이 있습니다.',
  });

  // 5. 콧방울 — 재백궁 하단
  const nw = lv(f.noseWing);
  if (nw !== 0) {
    push('재물', nw * 2, `재백궁(콧방울)이 ${nw > 0 ? '크다' : '작다'}`);
  }
  notes.push({
    palace: '재백궁 (콧방울)',
    text: nw > 0
      ? '콧방울이 두툼하고 탄력 있게 발달했습니다. 관상에서는 재백궁의 금고로 보아 들어온 재물과 실속을 든든하게 갈무리하고 지키는 힘이 크다고 봅니다. 생활의 기반을 알뜰하게 다지며, 실질적인 결실을 챙기는 실용적 감각이 발달한 상으로 해석합니다.'
      : nw < 0
        ? '콧방울이 갸름하고 아담한 편입니다. 관상에서는 물질을 쥐고 쌓아두기보다 재능이나 가치를 널리 순환시키는 데 무게를 두는 상으로 봅니다. 소유에 지나치게 얽매이지 않고 자유롭게 활동하며 새로운 흐름을 만들어가는 재능이 돋보입니다.'
        : '콧방울이 적당한 두께로 도톰하게 균형을 잘 이루고 있습니다. 관상에서는 재물을 벌어들이는 통로와 모아두는 곳이 서로 모자람 없이 조화를 이룬다고 봅니다. 과도한 낭비와 인색함 사이에서 실속 있는 소비와 저축의 균형을 슬기롭게 유지해 나가며 생활의 기반을 알뜰하게 다집니다.',
  });

  // 6. 입 — 출납관
  const ms = lv(f.mouthSize);
  if (ms !== 0) {
    push('표현력', ms, `출납관(입)이 ${ms > 0 ? '크다' : '작다'}`);
    push('재물', ms, `출납관(입)이 ${ms > 0 ? '크다' : '작다'}`);
  }
  notes.push({
    palace: '출납관 (입)',
    text: ms > 0
      ? '입이 시원하고 큰 편입니다. 관상에서는 입을 출납관(出納官)으로 보아 말과 표현의 폭이 넓고 호방하며 먹을 복이 풍족하다고 봅니다. 대범하게 포부를 밝히고 사람들과 적극적으로 교류하며 큰 무대에서 활약하기에 어울리는 기운을 품고 있습니다.'
      : ms < 0
        ? '입이 아담하고 단아한 편입니다. 관상에서는 말을 함부로 내뱉지 않고 신중하게 가려 하며, 불필요한 구설을 피하는 조심성으로 봅니다. 깊이 생각한 뒤 꼭 필요한 말을 조리 있게 전하며, 소수의 친밀한 관계에서 진면목을 보이는 상으로 해석합니다.'
        : '입 크기가 보통으로 단정하고 다부지게 다물어져 있습니다. 관상에서는 출납관의 흐름이 좋아 말과 표현이 경솔하지도 과묵하지도 않아 때와 장소에 알맞게 소통하는 힘으로 봅니다. 자신의 뜻을 명확하면서도 모나지 않게 전하여 주변에 편안한 신뢰감과 안정감을 전하는 균형이 있습니다.',
  });

  // 7. 입술 — 출납관
  const lt = lv(f.lipThickness);
  if (lt !== 0) {
    push('대인관계', lt, `입술이 ${lt > 0 ? '두껍다' : '얇다'}`);
  }
  notes.push({
    palace: '출납관 (입술)',
    text: lt > 0
      ? '입술이 도톰하고 살집이 풍부합니다. 관상에서는 정(情)이 두텁고 정감이 넘치며 사람을 대할 때 따뜻한 배려와 온기를 건네는 성정으로 봅니다. 감수성이 풍부하고 타인의 마음에 깊이 공감하여 주변에 온정을 나누는 매력이 돋보입니다.'
      : lt < 0
        ? '입술이 얇고 단정한 편입니다. 관상에서는 정에 쉽게 얽매이기보다 객관적인 이치와 합리적 판단을 앞세우는 성정으로 봅니다. 맺고 끊음이 명확하며 사사로운 감정에 치우치지 않고 공정하게 상황을 판단하는 이성적 면모가 강합니다.'
        : '입술 두께가 위아래 고르고 단정하게 알맞습니다. 관상에서는 정감과 이성의 균형이 잘 잡혀 있어, 정에 휘둘려 일을 그르치지도 않고 차갑게 거리를 두지도 않는 원만한 온도를 유지한다고 봅니다. 사람을 대할 때 적절한 거리감과 친절함을 지켜 오래가는 깊은 유대를 형성합니다.',
  });

  // 8. 턱 — 노복궁
  const jd = lv(f.jawDevelopment);
  if (jd !== 0) {
    push('인내', jd * 2, `노복궁(턱)이 ${jd > 0 ? '발달했다' : '갸름하다'}`);
    push('안정성', jd, `노복궁(턱)이 ${jd > 0 ? '발달했다' : '갸름하다'}`);
  }
  notes.push({
    palace: '노복궁 (턱)',
    text: jd > 0
      ? '턱선이 넓고 단단하게 발달해 있습니다. 관상에서는 턱을 노복궁(奴僕宮)이자 말년의 터전으로 보아, 세월이 흐를수록 끈기와 뚝심이 빛을 발한다고 봅니다. 쉽게 물러서지 않는 지구력과 주변 사람을 챙기는 넉넉한 품성을 갖춘 상으로 해석합니다.'
      : jd < 0
        ? '턱선이 날렵하고 갸름한 편입니다. 관상에서는 긴 지구력보다는 빠른 감각과 민첩한 두뇌 회전으로 승부하는 성향으로 봅니다. 고여 있는 상태를 피하고 시대의 변화나 유행을 빠르게 읽어내어 기민하게 움직일 때 장점이 잘 드러납니다.'
        : '턱선이 너무 모나거나 갸름하지 않고 원만하고 단단하게 받쳐줍니다. 관상에서는 노복궁의 힘이 안정되어 있어 어떤 일에 착수하든 중도에 포기하지 않고 꾸준히 결실을 맺는 든든함으로 봅니다. 시간이 흐르고 경험이 쌓일수록 신뢰와 안정이 차곡차곡 쌓여가는 대기만성의 형세입니다.',
  });

  // 9. 광대 — 권골
  const cb = lv(f.cheekbone);
  if (cb !== 0) {
    push('리더십', cb, `권골(광대)이 ${cb > 0 ? '발달했다' : '평평하다'}`);
    push('추진력', cb, `권골(광대)이 ${cb > 0 ? '발달했다' : '평평하다'}`);
  }
  notes.push({
    palace: '권골 (광대)',
    text: cb > 0
      ? '광대가 발달하여 얼굴의 중심을 힘차게 잡아줍니다. 관상에서는 광대를 권골(權骨)로 보아, 스스로 주도권을 쥐고 능동적으로 환경을 이끌어가려는 책임감과 의지가 크다고 봅니다. 난관이 닥쳐도 뒤로 숨지 않고 당당히 돌파해 나가는 장점이 있습니다.'
      : cb < 0
        ? '광대가 평평하고 도드라지지 않았습니다. 관상에서는 남의 위에 서서 권세를 부리기보다 동등한 입장에서 화합하고 뒤를 든든히 받쳐주는 성향으로 봅니다. 날카로운 경쟁을 피하고 평화롭게 실속을 차리며 자기 자리를 지키는 처세에 능합니다.'
        : '광대가 적당히 부드러운 살집에 감싸여 온화한 곡선을 이룹니다. 관상에서는 주변 사람에게 위압감을 주지 않으면서도 내실 있는 권위와 주관을 지키는 모양으로 봅니다. 튀지 않으면서도 맡은 자리에서 확실하게 입지를 다져나가며 사람들과 조화롭게 협력하는 미덕을 지니고 있습니다.',
  });

  // 10. 얼굴형
  const shapeRules: Record<FaceFeatures['faceShape'], { axis: TraitSignal['axis']; score: 1 | -1 }[]> = {
    round: [{ axis: '대인관계', score: 1 }, { axis: '안정성', score: 1 }],
    square: [{ axis: '인내', score: 1 }, { axis: '추진력', score: 1 }],
    oval: [{ axis: '안정성', score: 1 }],
    long: [{ axis: '학습·직관', score: 1 }, { axis: '인내', score: -1 }],
    heart: [{ axis: '학습·직관', score: 1 }, { axis: '표현력', score: 1 }],
  };
  for (const r of shapeRules[f.faceShape]) {
    push(r.axis, r.score, `얼굴형이 ${FACE_SHAPE_LABEL[f.faceShape]}`);
  }
  notes.push({
    palace: '얼굴형',
    text: {
      round: '둥근형 얼굴입니다. 모나지 않고 둥글둥글한 모양새처럼 사람의 마음을 편안하게 열어주며 원만한 대인관계를 이끌어냅니다. 친화력과 융통성이 뛰어나 어디서든 자연스럽게 어울리며 안정적인 터전을 만들어가는 기운을 지니고 있습니다.',
      square: '각진형 얼굴입니다. 굳건한 바위처럼 곧은 원칙과 흔들리지 않는 신념을 상징하며, 밀고 나가는 돌파력과 버티는 뚝심이 조화를 이룹니다. 시작한 일은 끝까지 완수해내는 책임감이 두터워 주변 사람들에게 큰 든든함을 주는 형세입니다.',
      oval: '계란형 얼굴입니다. 어느 한쪽으로 지나치게 치우치지 않고 이목구비의 기운을 골고루 받아 안는 조화로운 형태입니다. 순리와 자연스러움을 추구하며 상황 변화에 유연하게 적응하여 자신의 삶을 균형 있게 가꾸어나가는 모양새입니다. 원만한 인상으로 어디서든 호감을 이끌어냅니다.',
      long: '긴형 얼굴입니다. 생각이 깊고 사색을 즐기며 학문이나 전문 분야를 깊이 있게 파고드는 지혜로운 기운입니다. 한 자리에 정체되기보다는 끊임없이 높은 이상과 새로운 배움을 찾아 나서는 탐구심과 자존감이 잘 살아있는 상입니다. 남다른 전문성을 발휘하기에 좋습니다.',
      heart: '역삼각형 얼굴입니다. 두뇌 회전이 빠르고 아이디어가 반짝이며 자신의 감정과 생각을 산뜻하게 전달하는 재능이 돋보입니다. 감수성이 예민하고 직관이 뛰어나 예술이나 기획 등 창의적인 영역에서 남다른 두각을 나타내는 형태입니다. 영리하게 돌파구를 찾습니다.',
    }[f.faceShape],
  });

  // 묶어 보는 대목 (두 부위의 조합 — 최대 4쌍)
  if (f.foreheadWidth === 'high' && f.jawDevelopment === 'high') {
    combos.push({
      name: '초년과 말년의 조화 (이마·턱)',
      evidence: '관록궁(이마) 넓음 + 노복궁(턱) 발달',
      text: '이마가 시원하게 넓고 턱이 든든하게 발달하여 초년의 배움과 말년의 터전이 둘 다 두텁습니다. 시작하는 총명함과 끝을 지켜내는 뚝심이 함께 받쳐주어, 초년의 발판을 말년까지 안정되게 이어가는 훌륭한 균형입니다.',
    });
  }
  if (f.noseBridge === 'high' && f.cheekbone === 'low') {
    combos.push({
      name: '주관과 절제의 조화 (콧대·광대)',
      evidence: '재백궁(콧대) 높음 + 권골(광대) 평평함',
      text: '콧대가 높아 자기 뜻과 자존감은 분명하지만 광대가 평평하여 앞에 나서서 세를 과시하지는 않습니다. 자기 중심을 단단히 지키면서도 주변과 마찰 없이 묵묵히 실속을 다져가는 외유내강의 모양새입니다.',
    });
  }
  if (f.foreheadWidth === 'low' && f.jawDevelopment === 'high') {
    combos.push({
      name: '후반 안정의 흐름 (이마·턱)',
      evidence: '관록궁(이마) 좁음 + 노복궁(턱) 발달',
      text: '이마가 좁고 턱이 든든하여 초년에는 현장에서 몸으로 부딪쳐 터를 닦지만, 시간이 흐를수록 턱의 힘이 살아나 뒤로 갈수록 한결 두텁고 안정되는 대기만성형 흐름으로 봅니다.',
    });
  }
  if (f.noseBridge === 'high' && f.noseWing === 'high') {
    combos.push({
      name: '성취와 갈무리의 조화 (콧대·콧방울)',
      evidence: '재백궁(콧대) 높음 + 재백궁(콧방울) 발달',
      text: '콧대가 높고 콧방울이 두툼하여 추진력 있게 기회를 열고 들어온 재물과 성취를 든든하게 갈무리하는 힘이 함께합니다. 스스로 성과를 일으켜 차분히 결실을 챙기는 재백궁의 조화가 좋습니다.',
    });
  }

  const highlights = notes
    .filter((n) => n.palace !== '얼굴형')
    .slice(0, 4)
    .map((n) => n.text.split('.')[0] + '.');

  return { profile: { source: '관상', signals }, notes, combos, highlights };
}
