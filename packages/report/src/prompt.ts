/** 리포트 종류. 가격대가 다르므로 분량과 범위도 다르다. */
export type ReportKind = '사주' | '궁합' | '교차검증';

export interface ReportInput {
  kind: ReportKind;
  /** 룰 엔진이 낸 구조화 결과. 이 안에 없는 내용은 쓰면 안 된다. */
  data: unknown;
  /** 사람 이름 등 호칭. 없으면 '이 분'으로 쓴다 */
  subject?: string;
}

