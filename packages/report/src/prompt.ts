/**
 * 시스템 프롬프트. 입력과 무관하게 항상 같아야 캐시가 걸린다.
 * 종류별 구성 지시까지 포함하되, 사용자 데이터는 절대 넣지 않는다.
 */
export function buildSystemPrompt(kind: ReportKind): string {
  return `${SYSTEM_CORE}\n\n${OUTLINES[kind]}`;
}

/**
 * 사용자 메시지. 구조화 데이터를 그대로 싣는다.
 *
 * 요약하거나 골라 담지 않는다 — 모델이 근거를 인용할 수 있어야 하고,
 * 우리가 고르는 순간 그 선택이 또 하나의 판단이 되기 때문이다.
 */
export function buildUserMessage(input: ReportInput): string {
  const who = input.subject?.trim() || '이 분';
  return [
    `아래는 규칙 엔진이 계산한 ${input.kind} 결과입니다. 호칭은 "${who}"입니다.`,
    '',
    '이 데이터만 사용해 글을 쓰십시오. 여기에 없는 내용은 쓰지 마십시오.',
    '',
    '```json',
    JSON.stringify(input.data, null, 2),
    '```',
  ].join('\n');
}

/** 캐시 키에 쓸 정규화 문자열. 키 순서가 흔들리면 캐시가 새는 것을 막는다. */
export function canonicalize(value: unknown): string {
  if (value === null || typeof value !== 'object') return JSON.stringify(value) ?? 'null';
  if (Array.isArray(value)) return `[${value.map(canonicalize).join(',')}]`;
  const entries = Object.entries(value as Record<string, unknown>)
    .filter(([, v]) => v !== undefined)
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  return `{${entries.map(([k, v]) => `${JSON.stringify(k)}:${canonicalize(v)}`).join(',')}}`;
}
