/** 급수 합산. tau = 율리우스 천년수. 반환 단위는 계수 단위(1e-8). */
function sumSeries(series: number[][][], tau: number): number {
  let total = 0;
  for (let i = series.length - 1; i >= 0; i--) {
    let s = 0;
    for (const [a, b, c] of series[i]) s += a * Math.cos(b + c * tau);
    total = total * tau + s;
  }
  return total * 1e-8;
}

/**
 * 장동(nutation) 황경 성분 Δψ, 단위 초(").
 * 주요 4항만 사용 — 잔차 약 0.5"로 절입시각에 미치는 영향은 1초 미만.
 */
function nutationInLongitude(t: number): number {
  const omega = (125.04452 - 1934.136261 * t) * DEG;
  const lSun = (280.4665 + 36000.7698 * t) * DEG;
  const lMoon = (218.3165 + 481267.8813 * t) * DEG;
  return (
    -17.2 * Math.sin(omega) -
    1.32 * Math.sin(2 * lSun) -
    0.23 * Math.sin(2 * lMoon) +
    0.21 * Math.sin(2 * omega)
  );
}

/**
 * 주어진 JD(TT 근사)에서 태양의 겉보기 황경(도, 0-360).
 * 지구 황경 + 180° → FK5 보정 → 장동 → 광행차.
 */
export function apparentSolarLongitude(jd: number): number {
  const t = (jd - 2451545) / 36525;
  const tau = t / 10;

  const earthL = sumSeries(EARTH_L, tau); // rad
  const radius = sumSeries(EARTH_R, tau); // AU

  // 지구에서 본 태양 = 태양에서 본 지구 + 180°
  let theta = (earthL / DEG + 180) % 360;
  if (theta < 0) theta += 360;

  // VSOP87 → FK5 보정 (Meeus 25.9).
  // 두 번째 항은 tan(황위)에 비례하는데 태양의 황위는 사실상 0이므로 소거된다.
  theta += -0.09033 / 3600;

  // 장동 + 광행차
  const lambda = theta + nutationInLongitude(t) / 3600 - 20.4898 / radius / 3600;

  return ((lambda % 360) + 360) % 360;
}

/**
 * ΔT (TT − UT) 근사, 단위 초. Espenak/Meeus 다항식.
 * 절입시각을 UT 기준으로 내기 위해 필요하다. 1900년 이후 오차는 수 초 수준.
 */
export function deltaT(year: number, month: number): number {
  const y = year + (month - 0.5) / 12;
  if (y >= 2005 && y < 2050) {
    const t = y - 2000;
    return 62.92 + 0.32217 * t + 0.005589 * t * t;
  }
  if (y >= 1986 && y < 2005) {
    const t = y - 2000;
    return (
      63.86 + 0.3345 * t - 0.060374 * t * t + 0.0017275 * t ** 3 +
      0.000651814 * t ** 4 + 0.00002373599 * t ** 5
    );
  }
  if (y >= 1961 && y < 1986) {
    const t = y - 1975;
    return 45.45 + 1.067 * t - (t * t) / 260 - (t ** 3) / 718;
  }
  if (y >= 1941 && y < 1961) {
    const t = y - 1950;
    return 29.07 + 0.407 * t - (t * t) / 233 + (t ** 3) / 2547;
  }
  if (y >= 1920 && y < 1941) {
    const t = y - 1920;
    return 21.20 + 0.84493 * t - 0.076100 * t * t + 0.0020936 * t ** 3;
  }
  if (y >= 1900 && y < 1920) {
    const t = y - 1900;
    return (
      -2.79 + 1.494119 * t - 0.0598939 * t * t + 0.0061966 * t ** 3 - 0.000197 * t ** 4
    );
  }
  if (y >= 2050) {
    const t = y - 2000;
    return 62.92 + 0.32217 * t + 0.005589 * t * t;
  }
  // 1900년 이전 — 대략값
  const u = (y - 1820) / 100;
  return -20 + 32 * u * u;
}

/**
 * 태양 겉보기 황경이 targetDeg가 되는 순간을 구한다.
 * 반환은 **UT 기준 JD**.
 * @param targetDeg 0-360
 * @param guessJd   근방의 JD (UT)
 */
export function solveSolarLongitude(targetDeg: number, guessJd: number): number {
  let jdUt = guessJd;

  for (let i = 0; i < 60; i++) {
    const { y, m } = fromJulianDay(jdUt);
    const jdTt = jdUt + deltaT(y, m) / 86400;

    let diff = apparentSolarLongitude(jdTt) - targetDeg;
    // -180..180 으로 정규화 (0/360 경계 처리)
    while (diff > 180) diff -= 360;
    while (diff < -180) diff += 360;

    // 태양은 하루 약 0.9856° 이동
    const step = diff / 0.9856473;
    jdUt -= step;

    if (Math.abs(step) < 1e-7) break; // 약 0.01초
  }
  return jdUt;
}
