/**
 * 태양 겉보기 황경 계산 및 절기 절입시각 solver.
 *
 * VSOP87(Meeus, Astronomical Algorithms 2nd ed. Ch.25/32)의 절단 급수를 사용한다.
 * 절기 데이터를 테이블로 박지 않고 계산하는 이유:
 *   - 임의 연도로 확장 가능 (테이블은 수록 범위 밖에서 무력)
 *   - 코드가 짧고 외부 API 의존이 없음
 * 황경 정확도 약 1", 시각으로 환산하면 약 25초.
 */

const DEG = Math.PI / 180;

/** 그레고리력 → 율리우스일(JD). month는 1-12. day는 소수 허용. */
export function toJulianDay(y: number, m: number, d: number): number {
  let year = y;
  let month = m;
  if (month <= 2) {
    year -= 1;
    month += 12;
  }
  const a = Math.floor(year / 100);
  // 1582-10-15 이전은 율리우스력
  const isGregorian =
    y > 1582 || (y === 1582 && (m > 10 || (m === 10 && d >= 15)));
  const b = isGregorian ? 2 - a + Math.floor(a / 4) : 0;
  return (
    Math.floor(365.25 * (year + 4716)) +
    Math.floor(30.6001 * (month + 1)) +
    d +
    b -
    1524.5
  );
}

/** JD → { y, m, d(소수 포함) } */
export function fromJulianDay(jd: number): { y: number; m: number; d: number } {
  const z = Math.floor(jd + 0.5);
  const f = jd + 0.5 - z;
  let a = z;
  if (z >= 2299161) {
    const alpha = Math.floor((z - 1867216.25) / 36524.25);
    a = z + 1 + alpha - Math.floor(alpha / 4);
  }
  const b = a + 1524;
  const c = Math.floor((b - 122.1) / 365.25);
  const dd = Math.floor(365.25 * c);
  const e = Math.floor((b - dd) / 30.6001);
  const day = b - dd - Math.floor(30.6001 * e) + f;
  const month = e < 14 ? e - 1 : e - 13;
  const year = month > 2 ? c - 4716 : c - 4715;
  return { y: year, m: month, d: day };
}

