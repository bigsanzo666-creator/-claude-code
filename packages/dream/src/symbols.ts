/**
 * 꿈에 나오는 것들의 표.
 *
 * ## 왜 모델을 부르지 않는가
 *
 * 꿈해몽은 **공짜로 내놓는 것**이다. 공짜인데 손님이 누를 때마다 모델을 부르면
 * 사람이 몰릴수록 돈이 나간다. 누가 장난으로 천 번을 누르면 그날 예산이 탄다.
 * 그래서 여기 있는 것은 전부 표에서 꺼내 온다 — **원가가 0이다.**
 *
 * ## 이 표는 무엇인가
 *
 * 한국에서 오래 전해 내려온 해몽이다. 새로 지어낸 것이 아니라, 흔히 알려진
 * 풀이를 낱말별로 모아 둔 것이다. 지어낸 것이 하나도 없어야 손님이
 * 「어디서 본 것 같은데」 하고 믿는다.
 *
 * ## 겁주지 않는다
 *
 * 해몽으로 장사하는 데들이 제일 많이 하는 짓이 겁주기다. 「이 꿈은 흉몽입니다,
 * 부적을 쓰셔야 합니다」로 끝난다. 우리는 그렇게 하지 않는다.
 *
 * 그래서 낱말마다 `tone` 을 둔다. `흉` 으로 잡힌 것도 **무엇을 조심하라**로
 * 적지, **무슨 일이 닥친다**로 적지 않는다. 죽음·피·이빨처럼 놀라기 쉬운
 * 꿈일수록 전통 해몽에서는 오히려 좋게 보는 경우가 많다 — 그 사실을 먼저 적는다.
 *
 * ## 낱말을 어떻게 찾는가
 *
 * 손님은 「돼지꿈 꿨어요」라고도 쓰고 「커다란 돼지가 집으로 들어왔어요」라고도
 * 쓴다. 그래서 낱말마다 **같이 쓰는 말**(`words`)을 여럿 달아 둔다.
 * 찾는 일은 `read.ts` 가 한다.
 */

