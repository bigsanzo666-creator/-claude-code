/** 그 상품에 나오는 말만, 위 표에 적은 순서대로 */
export function termsOf(productId: string): Term[] {
  const keys = TERMS_OF_PRODUCT[productId];
  if (!keys) return [];
  const 본 = new Set<string>();
  return keys
    .filter((k) => (본.has(k) ? false : (본.add(k), true)))
    .map((k) => GLOSSARY[k])
    .filter((t): t is Term => Boolean(t));
}
