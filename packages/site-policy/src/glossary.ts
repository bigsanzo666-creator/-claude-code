/** 글 안에 실제로 나온 말만 골라낸다. 순서는 위 표에 적은 순서 그대로 */
export function termsIn(texts: string[]): Term[] {
  const 전체 = texts.join(' ');
  return Object.entries(GLOSSARY)
    .filter(([key]) => 전체.includes(key))
    .map(([, t]) => t);
}

