/**
 * 광고 대본.
 *
 * ## 여기만 고치면 된다
 *
 * 영상을 새로 만들려면 아래 표에 한 칸을 더 적는다. 코드는 건드리지 않는다.
 * 적고 나서 `node --experimental-strip-types 광고/만들기.ts` 를 부르면 된다.
 *
 * ## 누구에게 파는가
 *
 * 온라인 사주를 제일 많이 쓰는 사람은 10대 후반~20대 후반 여성이고,
 * **실제로 돈을 내는 사람은 26세 이상 여성**이 압도적이다.
 * 그래서 첫 문장은 전부 **스물예닐곱 살 여자가 혼자 중얼거릴 법한 말**로 쓴다.
 *
 * 다만 값이 큰 상품(작명 89,900·149,000원, 택일 59,000원, 명절 39,900원)은
 * 30대가 산다. 그쪽은 따로 겨냥을 잡는다 — `겨냥` 칸에 적어 둔다.
 *
 * ## 첫 문장 쓰는 법
 *
 * 질문하지 마라. **혼잣말을 적어라.**
 *   ✗ 「당신의 연애운이 궁금하신가요?」   — 광고처럼 들린다. 손이 지나간다
 *   ○ 「이번엔 다를 줄 알았는데」          — 자기 이야기다. 손이 멈춘다
 *
 * ## 거짓말을 적지 않는다
 *
 * 「무료」·「0원」은 **실제로 값을 받지 않는 것**에만 쓴다 —
 * 여덟 글자·오행·대운, 그리고 꿈해몽. 유료 상품 옆에 적으면
 * 표시광고법상 거짓·과장광고다. `verify.ts` 가 이걸 본다.
 *
 * ## 겁주지 않는다
 *
 * 「큰일 난다」·「막혔다」·「지금 안 보면」은 쓰지 않는다. 사이트에서 안 쓰는 말을
 * 광고에서 쓰면 들어와서 실망한다. 그게 환불로 돌아온다.
 */

/** 한 컷 */
export interface 컷 {
  /** assets 아래 경로. 예: '신령계문.mp4', '대면상담/재신령대면상담.mp4' */
  영상: string;
  /** 원본에서 몇 초부터 쓸 것인가 */
  시작: number;
  /** 몇 초 쓸 것인가 */
  길이: number;
  /** 큰 글씨. <em>로 감싼 곳이 금색이 된다. <br>로 줄을 나눈다 */
  큰글씨: string;
  /** 작은 글씨. 없어도 된다 */
  작은글씨?: string;
  /** 참이면 글씨를 화면 한가운데에 둔다 (첫 컷에만 쓴다) */
  가운데?: boolean;
}

/** 한 편 */
export interface 광고 {
  /** 파일 이름에 쓰인다. 영문·숫자·밑줄만 */
  id: string;
  /** 사람이 알아보는 이름 */
  이름: string;
  /** 누구에게 보일 것인가. 인스타 광고 만들 때 그대로 넣는다 */
  겨냥: string;
  /** 눌렀을 때 보낼 곳. 카탈로그에 있는 상품 id, 또는 'free'(무료 사주) */
  보낼곳: string;
  컷: 컷[];
}

